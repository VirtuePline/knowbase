def main() -> None:
    DEMO_DIR.mkdir(parents=True, exist_ok=True)

    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "故障维修记录"
    for row in MAINTENANCE_ROWS:
        sheet.append(row)
    for column, width in zip("ABCDEFGHIJ", (16, 12, 16, 12, 40, 60, 16, 18, 10, 10)):
        sheet.column_dimensions[column].width = width
    xlsx_path = DEMO_DIR / "设备故障维修记录台账_示例.xlsx"
    workbook.save(xlsx_path)

    md_path = DEMO_DIR / "MES运维记录_示例.md"
    md_path.write_text(MES_MD, encoding="utf-8")

    print(f"已生成：{xlsx_path}")
    print(f"已生成：{md_path}")
    print("导入方式：python -m app.cli ingest knowledge_base/demo")


if __name__ == "__main__":
    main()
